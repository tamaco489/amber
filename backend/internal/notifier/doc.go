// Package notifier は、デプロイの EventBridge のイベントを受け、デプロイごとに 1 つの Slack のスレッドにまとめる
//
// # 流れ
//
// 1 つのイベントを、次の手順で処理する。手順ごとに済んだかを DynamoDB に残し、再試行で流し直しても同じ結果になるようにする。
//
//  1. 親の投稿を用意する。そのデプロイで最初に届いたイベント (開始か進行中。順番は入れ替わる) が、chat.postMessage で親を投稿する
//  2. スレッドに返信する (最初のイベントも返信する)
//  3. 親を書き換える (開始で起動した人とリンクを埋める、ロールバック・完了・失敗で色と見出しを変える)
//  4. 完了と失敗では、親にスタンプを付ける
//
// 手順の記録とテーブルのアイテムの置き方は、internal/dynamodb に書く。
//
// 手順は「印を付ける (条件付きの書き込み) → Slack を呼ぶ → 済んだ印を付ける」の順に進める。
// 同じイベントが同時に 2 回届いても、印を付けられるのは片方だけで、もう片方はエラーを返して Lambda の再試行に回る。
// Slack を呼んだあと、済んだ印を付ける前に止まったときだけ、印の期限が切れてからの再試行で、同じ投稿がもう 1 件付きうる。
