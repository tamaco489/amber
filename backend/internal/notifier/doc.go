// Package notifier は、デプロイの EventBridge のイベントを受け、デプロイごとに 1 つの Slack のスレッドにまとめる
//
// # 流れ
//
// 1 つのイベントを、次の手順で処理する。手順ごとに済んだかを DynamoDB に残し、再試行で流し直しても同じ結果になるようにする。
//
//  1. 親の投稿を用意する。そのデプロイで最初に届いたイベント (開始か進行中。順番は入れ替わる) が、chat.postMessage で親を投稿する
//  2. スレッドに返信する (最初のイベントも返信する)
//  3. 親を書き換える (開始で起動した人とリンクを埋める、ロールバック・完了・失敗で色と見出しを変える)
//  4. 完了と失敗では、親にスタンプを付ける
//
// # DynamoDB のアイテム
//
// テーブルのパーティションキーは、文字列の pk だけ (ソートキーはない)。expires_at は TTL の属性 (Unix 秒) で、30 日後に消える。
//
// 親の投稿 (pk = "deployment#<デプロイ ID>")
//
//	ts               S  親の投稿の ts
//	channel          S  投稿したチャンネルの ID
//	service          S  サービスの名前
//	status           S  deploying / rolling_back / completed / failed
//	version          S  バージョン (Git のタグ。開始が届くまでは無い)
//	actor            S  起動した人 (同上)
//	run_url          S  GitHub Actions の実行の URL (同上)
//	task_definition  S  タスク定義の ARN (同上)
//	completed_at     S  完了した時刻 (RFC 3339)
//	rev              N  書き換えるたびに 1 ずつ増やす (楽観ロック。同時に届いたイベントが、互いの書き換えを消さないようにする)
//	expires_at       N  TTL
//
// 手順の記録 (pk = "step#<手順のキー>")
//
//	lease_until  N  処理中の印 (Unix 秒)。この時刻までは、ほかの呼び出しは同じ手順を進めない
//	done         BOOL  済んだ印。あれば、その手順は飛ばす
//	expires_at   N  TTL
//
// 手順のキーは次のとおり。
//
//	parent#<デプロイ ID>       親の投稿 (デプロイごとに 1 つ。どのイベントが作ったかによらない)
//	<イベント ID>#reply        スレッドへの返信
//	<イベント ID>#parent       親の書き換え
//	<イベント ID>#reaction     スタンプ
//
// 手順は「印を付ける (条件付きの書き込み) → Slack を呼ぶ → 済んだ印を付ける」の順に進める。
// 同じイベントが同時に 2 回届いても、印を付けられるのは片方だけで、もう片方はエラーを返して Lambda の再試行に回る。
// Slack を呼んだあと、済んだ印を付ける前に止まったときだけ、印の期限が切れてからの再試行で、同じ投稿がもう 1 件付きうる。
